"""Read-only resource samples, separating the project pods from total node usage."""

import argparse
import json
import os
import subprocess
import time
from datetime import datetime, timezone
from pathlib import Path


def output(*args):
    result = subprocess.run(args, text=True, capture_output=True, check=False)
    return {"exit_code": result.returncode, "stdout": result.stdout, "stderr": result.stderr}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--scenario", choices=["idle", "load", "backfill", "backup", "restart"], required=True
    )
    parser.add_argument("--seconds", type=int, default=60)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    if not 0 <= args.seconds <= 3600:
        parser.error("seconds must be between 0 and 3600")
    namespace = os.getenv("NAMESPACE", "data-stack")
    records = []
    deadline = time.monotonic() + args.seconds
    while True:
        records.append(
            {
                "at": datetime.now(timezone.utc).isoformat(),
                "node": output("kubectl", "top", "nodes"),
                "project": output("kubectl", "-n", namespace, "top", "pods", "--containers"),
                "pods": output("kubectl", "-n", namespace, "get", "pods"),
                "disk": output("df", "-h", "/"),
            }
        )
        if time.monotonic() >= deadline:
            break
        time.sleep(min(10, max(0, deadline - time.monotonic())))
    Path(args.output).parent.mkdir(parents=True, exist_ok=True)
    Path(args.output).write_text(
        json.dumps(
            {"scenario": args.scenario, "namespace": namespace, "samples": records}, indent=2
        )
    )
    print(f"Wrote {len(records)} samples to {args.output}; no load was generated by this script")


if __name__ == "__main__":
    main()
